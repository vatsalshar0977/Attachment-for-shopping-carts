def make_top_mic(materials):
    bronze = materials["bronze"]
    bright = materials["bright_bronze"]
    dark_bronze = materials["dark_bronze"]
    grille_mat = materials["grille"]
    weave_mat = materials["weave"]

    axis = Vector((0.220, -0.160, 0.962)).normalized()
    axis_origin = Vector((-0.185, 0.035, 1.205))
    u, v = plane_basis(axis)

    barrel_start = -0.055
    barrel_end = 0.600
    barrel_center = axis_origin + axis * ((barrel_start + barrel_end) * 0.5)
    barrel = make_oriented_cylinder(
        "Angled_Microphone_Barrel", 0.304, barrel_end - barrel_start,
        barrel_center, axis, dark_bronze, bevel=0.026,
    )

    # Satin shoulder and the distinct machined knurl ring.
    make_oriented_torus("Barrel_Lower_Shoulder", 0.300, 0.016,
                        axis_origin + axis * 0.035, axis, bright)
    band_bottom, band_top = 0.585, 0.805
    band_center = axis_origin + axis * ((band_bottom + band_top) * 0.5)
    make_annular_collar(
        "Diamond_Knurled_Bronze_Collar", axis_origin, axis,
        band_bottom, band_top, inner_radius=0.278, outer_radius=0.356,
        material=bronze,
    )
    make_oriented_torus("Knurl_Lower_Bright_Rim", 0.348, 0.009,
                        axis_origin + axis * (band_bottom + 0.012), axis, bright)
    make_oriented_torus("Knurl_Upper_Bright_Rim", 0.348, 0.010,
                        axis_origin + axis * (band_top - 0.010), axis, bright)

    # Two opposed helical families create an even, machined diamond knurl.
    knurl_splines = []
    line_count = 72
    point_count = 30
    ring_radius = 0.358
    for direction in (-1.0, 1.0):
        for line in range(line_count):
            coords = []
            phase = 2.0 * math.pi * line / line_count
            for step in range(point_count):
                t = step / (point_count - 1)
                angle = phase + direction * (2.0 * math.pi * 4.7 * t)
                pos = (axis_origin + axis * (band_bottom + 0.014 + t * (band_top-band_bottom-0.028))
                       + ring_radius * (u * math.cos(angle) + v * math.sin(angle)))
                coords.append(tuple(pos))
            knurl_splines.append(coords)
    make_poly_curve("Crosshatched_Diamond_Knurl", knurl_splines, 0.0019, dark_bronze, 1)

    # Top lip, inner well, and a fine woven mesh recessed inside the aperture.
    top_t = band_top
    make_oriented_torus("Machined_Microphone_Port_Lip", 0.310, 0.024,
                        axis_origin + axis * (top_t - 0.001), axis, bright)
    make_oriented_torus("Inner_Port_Seat", 0.282, 0.009,
                        axis_origin + axis * (top_t - 0.026), axis, dark_bronze)
    disk_t = top_t - 0.039
    disk_center = axis_origin + axis * disk_t
    radius = 0.274
    ring_count = 128
    disk_verts = [tuple(disk_center)]
    for i in range(ring_count):
        theta = 2.0 * math.pi * i / ring_count
        p = disk_center + radius * (u * math.cos(theta) + v * math.sin(theta))
        disk_verts.append(tuple(p))
    disk_faces = [(0, i + 1, ((i + 1) % ring_count) + 1) for i in range(ring_count)]
    disk_mesh = bpy.data.meshes.new("Recessed microphone mesh backing")
    disk_mesh.from_pydata(disk_verts, [], disk_faces)
    disk_mesh.materials.append(grille_mat)
    disk_mesh.update()
    disk = bpy.data.objects.new("Recessed_Black_Grille_Backing", disk_mesh)
    bpy.context.collection.objects.link(disk)

    weave_splines = []
    wire_radius = 0.266
    pitch = 0.0105
    values = []
    steps = int((2.0 * wire_radius) / pitch)
    for i in range(-steps // 2, steps // 2 + 1):
        q = i * pitch
        if abs(q) >= wire_radius:
            continue
        half = math.sqrt(wire_radius * wire_radius - q*q)
        p1 = disk_center + u*(-half) + v*q + axis*0.0015
        p2 = disk_center + u*( half) + v*q + axis*0.0015
        weave_splines.append([tuple(p1), tuple(p2)])
        p3 = disk_center + u*q + v*(-half) + axis*0.0018
        p4 = disk_center + u*q + v*( half) + axis*0.0018
        values.append([tuple(p3), tuple(p4)])
    weave_splines.extend(values)
    make_poly_curve("Fine_Woven_Microphone_Grille", weave_splines, 0.00115, weave_mat, 1)

    # Thin concentric lines are visible through the woven diaphragm as a second
    # layer of the recessed black mesh, not as a shiny decorative button.
    for idx, r in enumerate((0.090, 0.165, 0.235)):
        coords = []
        for j in range(129):
            theta = 2.0 * math.pi * j / 128
            p = disk_center + axis*0.002 + r*(u*math.cos(theta) + v*math.sin(theta))
            coords.append(tuple(p))
        make_poly_curve(f"Grille_Support_Ring_{idx+1}", [coords], 0.0009, dark_bronze, 1)

    top_center = axis_origin + axis * (top_t + 0.02)
    return axis, axis_origin, top_center


