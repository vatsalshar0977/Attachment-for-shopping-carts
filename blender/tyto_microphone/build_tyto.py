def principled_material(name, color, metallic=0.0, roughness=0.35,
                        noise_scale=None, bump_strength=0.08,
                        bump_distance=0.008):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1.0)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    shader = nodes.get("Principled BSDF")
    shader.inputs["Base Color"].default_value = (*color, 1.0)
    shader.inputs["Metallic"].default_value = metallic
    shader.inputs["Roughness"].default_value = roughness
    if noise_scale:
        noise = nodes.new("ShaderNodeTexNoise")
        noise.inputs["Scale"].default_value = noise_scale
        noise.inputs["Detail"].default_value = 2.0
        noise.inputs["Roughness"].default_value = 0.62
        bump = nodes.new("ShaderNodeBump")
        bump.inputs["Strength"].default_value = bump_strength
        bump.inputs["Distance"].default_value = bump_distance
        links.new(noise.outputs["Fac"], bump.inputs["Height"])
        links.new(bump.outputs["Normal"], shader.inputs["Normal"])
    return mat


def emission_material(name, color=(1.0, 0.22, 0.025), strength=2.2):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1.0)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    nodes.clear()
    emission = nodes.new("ShaderNodeEmission")
    emission.inputs["Color"].default_value = (*color, 1.0)
    emission.inputs["Strength"].default_value = strength
    output = nodes.new("ShaderNodeOutputMaterial")
    mat.node_tree.links.new(emission.outputs["Emission"], output.inputs["Surface"])
    return mat


def set_active(obj):
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.context.view_layer.objects.active = obj


def apply_modifier(obj, modifier):
    set_active(obj)
    bpy.ops.object.modifier_apply(modifier=modifier.name)


def shade_smooth(obj):
    if obj.type == "MESH":
        for polygon in obj.data.polygons:
            polygon.use_smooth = True


def make_bezier_curve(name, points, bevel_depth, material, radii=None,
                      resolution=16, bevel_resolution=4):
    """Create a smooth 3D Bezier curve from world-space xyz points."""
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = resolution
    curve.bevel_depth = bevel_depth
    curve.bevel_resolution = bevel_resolution
    curve.resolution_u = resolution
    curve.use_fill_caps = True
    spline = curve.splines.new("BEZIER")
    spline.bezier_points.add(len(points) - 1)
    for i, (bp, co) in enumerate(zip(spline.bezier_points, points)):
        bp.co = co
        bp.handle_left_type = "AUTO"
        bp.handle_right_type = "AUTO"
        if radii is not None:
            bp.radius = radii[i]
    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    obj.data.materials.append(material)
    return obj


def make_poly_curve(name, splines, bevel_depth, material, bevel_resolution=2):
    """Create one curve object containing many polyline splines."""
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = 1
    curve.bevel_depth = bevel_depth
    curve.bevel_resolution = bevel_resolution
    curve.use_fill_caps = True
    for coords in splines:
        if len(coords) < 2:
            continue
        spline = curve.splines.new("POLY")
        spline.points.add(len(coords) - 1)
        for point, co in zip(spline.points, coords):
            point.co = (co[0], co[1], co[2], 1.0)
    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    obj.data.materials.append(material)
    return obj


def smooth_catmull_rom(values, samples_per_segment=10):
    """Centripetal-ish Catmull-Rom sampling for tuples of scalar values."""
    if len(values) < 2:
        return list(values)
    result = []
    n = len(values)
    for i in range(n - 1):
        p0 = values[max(0, i - 1)]
        p1 = values[i]
        p2 = values[i + 1]
        p3 = values[min(n - 1, i + 2)]
        for j in range(samples_per_segment):
            t = j / samples_per_segment
            t2 = t * t
            t3 = t2 * t
            row = []
            for k in range(len(p1)):
                v = 0.5 * (
                    2.0 * p1[k]
                    + (-p0[k] + p2[k]) * t
                    + (2.0*p0[k] - 5.0*p1[k] + 4.0*p2[k] - p3[k]) * t2
                    + (-p0[k] + 3.0*p1[k] - 3.0*p2[k] + p3[k]) * t3
                )
                row.append(v)
            result.append(tuple(row))
    result.append(tuple(values[-1]))
    return result


def make_oriented_cylinder(name, radius, depth, center, axis, material,
                           bevel=0.012, vertices=128):
    bpy.ops.mesh.primitive_cylinder_add(
        vertices=vertices, radius=radius, depth=depth,
        location=tuple(center),
    )
    obj = bpy.context.object
    obj.name = name
    axis = Vector(axis).normalized()
    obj.rotation_euler = axis.to_track_quat("Z", "Y").to_euler()
    obj.data.materials.append(material)
    if bevel > 0:
        mod = obj.modifiers.new("Machined edge radii", "BEVEL")
        mod.width = bevel
        mod.segments = 4
        mod.limit_method = "ANGLE"
        mod2 = obj.modifiers.new("Weighted corner normals", "WEIGHTED_NORMAL")
        mod2.keep_sharp = True
    shade_smooth(obj)
    return obj


def make_oriented_torus(name, major_radius, minor_radius, center, axis, material):
    bpy.ops.mesh.primitive_torus_add(
        major_segments=128, minor_segments=20,
        major_radius=major_radius, minor_radius=minor_radius,
        location=tuple(center),
    )
    obj = bpy.context.object
    obj.name = name
    obj.rotation_euler = Vector(axis).normalized().to_track_quat("Z", "Y").to_euler()
    obj.data.materials.append(material)
    shade_smooth(obj)
    return obj


def make_annular_collar(name, axis_origin, axis, t_bottom, t_top,
                         inner_radius, outer_radius, material):
    """Hollow, chamfered circular collar built as a turned annular profile."""
    axis = Vector(axis).normalized()
    u, v = plane_basis(axis)
    chamfer = min(0.018, (t_top - t_bottom) * 0.12)
    radial_chamfer = min(0.018, (outer_radius - inner_radius) * 0.2)
    profile = [
        (t_bottom + chamfer, inner_radius),
        (t_bottom + chamfer, outer_radius - radial_chamfer),
        (t_bottom, outer_radius),
        (t_top, outer_radius),
        (t_top - chamfer, outer_radius - radial_chamfer),
        (t_top - chamfer, inner_radius + radial_chamfer),
        (t_top, inner_radius),
        (t_bottom, inner_radius),
    ]
    ring_segments = 144
    vertices = []
    for axial_t, radius in profile:
        center = Vector(axis_origin) + axis * axial_t
        for i in range(ring_segments):
            angle = 2.0 * math.pi * i / ring_segments
            point = center + radius * (u * math.cos(angle) + v * math.sin(angle))
            vertices.append(tuple(point))
    faces = []
    for row in range(len(profile)):
        next_row = (row + 1) % len(profile)
        for i in range(ring_segments):
            next_i = (i + 1) % ring_segments
            a = row * ring_segments + i
            b = row * ring_segments + next_i
            c = next_row * ring_segments + next_i
            d = next_row * ring_segments + i
            faces.append((a, b, c, d))
    mesh = bpy.data.meshes.new(f"{name}_turned_mesh")
    mesh.from_pydata(vertices, [], faces)
    mesh.materials.append(material)
    mesh.update()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)
    # Recalculate closed annular normals robustly for the hollow rim.
    import bmesh
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(mesh)
    bm.free()
    shade_smooth(obj)
    return obj


def plane_basis(axis):
    axis = Vector(axis).normalized()
    u = Vector((1.0, 0.0, 0.0))
    u = (u - axis * u.dot(axis)).normalized()
    v = axis.cross(u).normalized()
    return u, v


def make_fused_shell(material):
    parts = []
    for index, (center, scale) in enumerate(SHELL_ELLIPSOIDS):
        bpy.ops.mesh.primitive_uv_sphere_add(
            segments=96, ring_count=64, radius=1.0, location=center,
        )
        obj = bpy.context.object
        obj.name = f"Shell_Form_{index + 1}"
        obj.scale = scale
        set_active(obj)
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        shade_smooth(obj)
        parts.append(obj)
    bpy.ops.object.select_all(action="DESELECT")
    for obj in parts:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    bpy.ops.object.join()
    body = bpy.context.object
    body.name = "TYTO_Satin_Bronze_Shell"
    # Voxel remesh fuses the swept, overlapping lobes into one continuous shell.
    remesh = body.modifiers.new("Fuse organic shell lobes", "REMESH")
    remesh.mode = "VOXEL"
    remesh.voxel_size = 0.014
    remesh.use_smooth_shade = True
    apply_modifier(body, remesh)
    smooth = body.modifiers.new("Sculpted surface polish", "SMOOTH")
    smooth.factor = 0.82
    smooth.iterations = 5
    apply_modifier(body, smooth)
    shade_smooth(body)
    body.data.materials.append(material)
    return body


def front_surface_y(x, z):
    """Front-most y of the union ellipsoids, with a soft fallback at edges."""
    candidates = []
    for center, scale in SHELL_ELLIPSOIDS:
        cx, cy, cz = center
        a, b, c = scale
        normalized = ((x-cx)/a)**2 + ((z-cz)/c)**2
        if normalized <= 1.0:
            candidates.append(cy - b * math.sqrt(max(0.0, 1.0 - normalized)))
    if candidates:
        return min(candidates)
    # The path is intentionally inset into the shell silhouette; this fallback
    # keeps the final few tapered vertices tucked into, rather than through, it.
    nearest = None
    for center, scale in SHELL_ELLIPSOIDS:
        cx, cy, cz = center
        a, b, c = scale
        normalized = ((x-cx)/a)**2 + ((z-cz)/c)**2
        penalty = max(0.0, normalized - 0.94)
        candidate = (penalty, cy - b * math.sqrt(max(0.05, 1.0-min(normalized, 0.99))))
        if nearest is None or candidate[0] < nearest[0]:
            nearest = candidate
    return nearest[1] if nearest else -0.26


def sample_spiral_path(samples_per_segment=10):
    return smooth_catmull_rom(SPIRAL_PATH, samples_per_segment)


def path_frame(samples, index):
    before = samples[max(0, index - 1)]
    after = samples[min(len(samples) - 1, index + 1)]
    dx = after[0] - before[0]
    dz = after[1] - before[1]
    length = max(1e-8, math.hypot(dx, dz))
    tangent = (dx / length, dz / length)
    normal = (-tangent[1], tangent[0])
    return tangent, normal


def ribbon_vertices(samples, segments=17, q_factor=-0.0, y_lift=0.010):
    vertices = []
    for i, row in enumerate(samples):
        x, z, width = row
        _, normal = path_frame(samples, i)
        taper = min(1.0, max(0.12, i / max(1, len(samples)*0.035)),
                    max(0.12, (len(samples)-1-i) / max(1, len(samples)*0.035)))
        local_width = width * taper
        for j in range(segments + 1):
            side = -1.0 + 2.0 * j / segments
            q = side * local_width
            px = x + normal[0] * q
            pz = z + normal[1] * q
            py = front_surface_y(px, pz) - y_lift
            vertices.append((px, py, pz))
    faces = []
    row_len = segments + 1
    for i in range(len(samples) - 1):
        for j in range(segments):
            a = i * row_len + j
            b = a + row_len
            faces.append((a, b, b + 1, a + 1))
    return vertices, faces


def make_spiral_inlay(material):
    samples = sample_spiral_path(12)
    verts, faces = ribbon_vertices(samples, segments=18, y_lift=0.008)
    mesh = bpy.data.meshes.new("Deep blue spiral inlay mesh")
    mesh.from_pydata(verts, [], faces)
    mesh.materials.append(material)
    mesh.update()
    obj = bpy.data.objects.new("Recessed_Navy_Spiral_Channel", mesh)
    bpy.context.collection.objects.link(obj)
    for polygon in mesh.polygons:
        polygon.use_smooth = True
    solidify = obj.modifiers.new("Inlay edge depth", "SOLIDIFY")
    solidify.thickness = 0.006
    solidify.offset = -1.0
    bevel = obj.modifiers.new("Soft inlay edge", "BEVEL")
    bevel.width = 0.004
    bevel.segments = 3
    return samples


def make_spiral_detail_lines(samples, bronze, led):
    trim_points = []
    led_points = []
    for i, (x, z, width) in enumerate(samples):
        _, normal = path_frame(samples, i)
        taper = min(1.0, max(0.14, i / max(1, len(samples)*0.035)),
                    max(0.14, (len(samples)-1-i) / max(1, len(samples)*0.035)))
        w = width * taper
        # A fine bronze return on the outside edge, plus the continuous amber LED.
        for q_factor, target in ((-0.79, trim_points), (0.73, led_points)):
            q = w * q_factor
            px, pz = x + normal[0]*q, z + normal[1]*q
            py = front_surface_y(px, pz) - (0.021 if target is trim_points else 0.026)
            target.append((px, py, pz))
    trim = make_poly_curve("Fine_Bronze_Inlay_Bead", [trim_points], 0.010, bronze, 3)
    led_obj = make_poly_curve("Continuous_Amber_Spiral_LED", [led_points], 0.0070, led, 3)
    led_obj.data.bevel_factor_start = 0.0
    led_obj.data.bevel_factor_end = 1.0
    # The line is mostly lit from the first frame; it completes a short trace by 0.8 s.
    led_obj.data.bevel_factor_end = 0.72
    led_obj.data.keyframe_insert(data_path="bevel_factor_end", frame=FRAME_START)
    led_obj.data.bevel_factor_end = 1.0
    led_obj.data.keyframe_insert(data_path="bevel_factor_end", frame=20)
    led_obj.data.bevel_factor_end = 1.0
    led_obj.data.keyframe_insert(data_path="bevel_factor_end", frame=FRAME_END)
    return trim, led_obj


def make_raised_eye(material, dark_material):
    # A small sculpted spiral lip sits in the centre of the inlay, echoing the
    # raised shell eye in the supplied reference.
    cx, cz = 0.105, 0.575
    points = []
    radii = []
    count = 72
    turns = 1.30
    for i in range(count):
        t = i / (count - 1)
        theta = -0.55 * math.pi + turns * 2.0 * math.pi * t
        radius = 0.138 * (1.0 - t) + 0.027
        x = cx + radius * math.cos(theta)
        z = cz + radius * math.sin(theta)
        y = front_surface_y(x, z) - 0.030
        points.append((x, y, z))
        radii.append(0.50 + 0.48 * math.sin(math.pi*t))
    eye = make_poly_curve("Raised_Spiral_Eye_Ridge", [points], 0.018, material, 4)
    # Dark recessed centre gives the coil a clear focal point without adding a button.
    center_y = front_surface_y(cx, cz) - 0.025
    bpy.ops.mesh.primitive_uv_sphere_add(
        segments=40, ring_count=24, radius=0.034,
        location=(cx, center_y, cz),
    )
    pupil = bpy.context.object
    pupil.name = "Spiral_Eye_Recess"
    pupil.scale = (1.0, 0.38, 1.0)
    pupil.data.materials.append(dark_material)
    shade_smooth(pupil)
    return eye


def make_shell_seam(material):
    # A fine lower-shell parting seam is visible on the right flank in the source.
    points_2d = [(0.405, 0.285), (0.440, 0.245), (0.468, 0.200), (0.482, 0.165)]
    points = [(x, front_surface_y(x, z) - 0.008, z) for x, z in points_2d]
    return make_bezier_curve("Lower_Shell_Parting_Seam", points, 0.0045, material, resolution=12)


