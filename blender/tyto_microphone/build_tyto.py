def render_stills(bundle, preview=False):
    scene = bundle["scene"]
    rig = bundle["rig"]
    led_obj = bpy.data.objects.get("Continuous_Amber_Spiral_LED")
    muted_led_curves = []
    if led_obj and led_obj.data.animation_data and led_obj.data.animation_data.action:
        for fcurve in led_obj.data.animation_data.action.fcurves:
            if fcurve.data_path == "bevel_factor_end":
                muted_led_curves.append((fcurve, fcurve.mute))
                fcurve.mute = True
    # Hold the camera at its reference hero angle and show the complete LED
    # trace for stills; the keyframed reveal remains intact for the animation.
    scene.frame_set(FRAME_START)
    rig.rotation_euler.z = 0.0
    if led_obj:
        led_obj.data.bevel_factor_end = 1.0
    bpy.context.view_layer.update()
    specs = [
        ("hero", bundle["hero"], "tyto_hero.png", 1240, 1536, 36),
        ("front", bundle["front"], "tyto_front_shell.png", 1040, 1280, 28),
        ("spiral", bundle["spiral"], "tyto_top_spiral.png", 1040, 1280, 30),
        ("profile", bundle["profile"], "tyto_side_profile.png", 1040, 1280, 28),
        ("grille", bundle["grille"], "tyto_knurl_macro.png", 1200, 1000, 32),
    ]
    for label, camera, filename, width, height, samples in specs:
        scene.camera = camera
        if preview:
            width = 720 if label != "grille" else 800
            height = 900 if label != "grille" else 680
            samples = 12
        set_camera_quality(scene, width, height, samples)
        out = RENDER_DIR / ("_tyto_preview.png" if preview else filename)
        scene.render.filepath = str(out)
        print(f"[TYTO] Rendering {label}: {width}x{height}, {samples} Cycles samples -> {out}", flush=True)
        bpy.ops.render.render(write_still=True)
        if preview:
            break
    for fcurve, was_muted in muted_led_curves:
        fcurve.mute = was_muted
    scene.camera = bundle["hero"]
    scene.frame_set(FRAME_START)
    set_camera_quality(scene, 1240, 1536, 36)
    scene.render.filepath = str(RENDER_DIR / "tyto_hero.png")
    bpy.context.view_layer.update()
    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND_PATH))


def locate_ffmpeg():
    if os.environ.get("FFMPEG"):
        return os.environ["FFMPEG"]
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except Exception:
        return shutil.which("ffmpeg")


def render_animation(bundle):
    scene = bundle["scene"]
    FRAMES_DIR.mkdir(parents=True, exist_ok=True)
    scene.camera = bundle["hero"]
    set_camera_quality(scene, 480, 600, 8)
    scene.render.filepath = str(FRAMES_DIR / "tyto_")
    scene.cycles.use_denoising = True
    for frame in range(FRAME_START, FRAME_END + 1):
        scene.frame_set(frame)
        scene.render.filepath = str(FRAMES_DIR / f"tyto_{frame:04d}.png")
        bpy.context.view_layer.update()
        bpy.ops.render.render(write_still=True)
        if frame % 12 == 0 or frame == FRAME_START:
            print(f"[TYTO] Animation frame {frame}/{FRAME_END}", flush=True)

    ffmpeg = locate_ffmpeg()
    if not ffmpeg:
        raise RuntimeError("FFmpeg not found. Install imageio-ffmpeg or set FFMPEG.")
    out = ANIMATION_DIR / "tyto_orbit_6s.mp4"
    command = [
        ffmpeg, "-y", "-hide_banner", "-loglevel", "error",
        "-framerate", str(FPS), "-start_number", str(FRAME_START),
        "-i", str(FRAMES_DIR / "tyto_%04d.png"),
        "-frames:v", str(FRAME_END), "-c:v", "libx264", "-preset", "medium",
        "-crf", "19", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
        str(out),
    ]
    print(f"[TYTO] Encoding six-second animation -> {out}", flush=True)
    subprocess.run(command, check=True)
    scene.frame_set(FRAME_START)
    scene.camera = bundle["hero"]
    set_camera_quality(scene, 1240, 1536, 36)
    scene.render.filepath = str(RENDER_DIR / "tyto_hero.png")
    bpy.ops.wm.save_as_mainfile(filepath=str(BLEND_PATH))
    print(f"[TYTO] Animation complete: {out.stat().st_size:,} bytes", flush=True)


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else sys.argv[1:]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stills", action="store_true", help="Render five product stills")
    parser.add_argument("--animation", action="store_true", help="Render 144 frames and encode MP4")
    parser.add_argument("--preview", action="store_true", help="Render a fast diagnostic preview")
    parser.add_argument("--no-save", action="store_true", help="Do not save the .blend")
    return parser.parse_args(argv)


def main():
    args = parse_args()
    bundle = build_scene()
    if args.preview:
        render_stills(bundle, preview=True)
    if args.stills:
        render_stills(bundle, preview=False)
    if args.animation:
        render_animation(bundle)
    if not args.no_save:
        bundle["scene"].frame_set(FRAME_START)
        bundle["scene"].camera = bundle["hero"]
        bpy.ops.wm.save_as_mainfile(filepath=str(BLEND_PATH))
    print(f"[TYTO] Editable Blender scene saved at {BLEND_PATH}", flush=True)


if __name__ == "__main__":
    main()
