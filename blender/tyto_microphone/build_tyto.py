def build_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for block in bpy.data.materials:
        if block.users == 0:
            bpy.data.materials.remove(block)

    RENDER_DIR.mkdir(parents=True, exist_ok=True)
    ANIMATION_DIR.mkdir(parents=True, exist_ok=True)
    BLEND_PATH.parent.mkdir(parents=True, exist_ok=True)
    materials = create_materials()

    body = make_fused_shell(materials["bronze"])
    samples = make_spiral_inlay(materials["navy"])
    make_spiral_detail_lines(samples, materials["shell_trim"], materials["led"])
    make_raised_eye(materials["bright_bronze"], materials["seam"])
    make_shell_seam(materials["seam"])
    axis, axis_origin, top_center = make_top_mic(materials)

    # A low-profile hidden shoe/pad is a construction seam, not an extra control.
    make_oriented_cylinder("Lower_Base_Seam", 0.175, 0.050,
                           (0.10, 0.012, 0.012), (0.0, 0.0, 1.0),
                           materials["seam"], bevel=0.009, vertices=96)

    scene = bpy.context.scene
    focus, orbit_rig, hero_camera = setup_studio(scene, materials)
    scene["TYTO_design_note"] = (
        "Reference-matched nautilus-shell camera/phone-rig microphone concept. "
        "Metal body, recessed navy spiral, amber light trace, diamond knurl, woven port."
    )
    scene["reference_image"] = str(ROOT / "references" / "tyto_bronze_render_reference.png")
    scene["microphone_axis"] = tuple(axis)
    scene["microphone_axis_origin"] = tuple(axis_origin)
    scene["microphone_top_center"] = tuple(top_center)

    # Static cameras for the product-sheet views.
    front_camera = make_camera("TYTO_Front_Detail_Camera", (0.0, -7.5, 1.55), (0.02, 0.0, 0.92), 72)
    spiral_camera = make_camera("TYTO_Spiral_Close_Camera", (1.20, -4.8, 2.35), (0.0, -0.05, 0.86), 84)
    profile_camera = make_camera("TYTO_Side_Profile_Camera", (6.3, -2.6, 2.75), (0.03, 0.0, 0.96), 72)
    grille_u, grille_v = plane_basis(axis)
    grille_camera = make_camera(
        "TYTO_Knurled_Port_Camera",
        tuple(top_center + axis * 1.70 + grille_u * 1.05 + grille_v * 0.18),
        tuple(top_center), 60,
    )
    scene.camera = hero_camera
    scene.frame_set(FRAME_START)
    # Save the native, editable scene before rendering any output.
